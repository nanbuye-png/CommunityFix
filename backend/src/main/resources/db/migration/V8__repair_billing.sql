ALTER TABLE repair_order
 ADD COLUMN facility_scope VARCHAR(16) NOT NULL DEFAULT 'LEGACY',
 ADD COLUMN location_text VARCHAR(200) NULL,
 ADD COLUMN billing_version INT NOT NULL DEFAULT 0;
CREATE TABLE repair_quote (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL, revision INT NOT NULL,
 items_json JSON NOT NULL, amount_fen BIGINT NOT NULL, reason VARCHAR(500) NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'PROPOSED', created_by BIGINT NOT NULL, decided_by BIGINT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), decided_at DATETIME(3) NULL,
 UNIQUE(order_id,revision), FOREIGN KEY(order_id) REFERENCES repair_order(id),
 CHECK(amount_fen>0), CHECK(status IN ('PROPOSED','ACCEPTED','REJECTED','SUPERSEDED'))
);
CREATE TABLE repair_bill (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL UNIQUE, quote_id BIGINT NOT NULL,
 payer_id BIGINT NOT NULL, amount_fen BIGINT NOT NULL, currency VARCHAR(3) NOT NULL DEFAULT 'CNY',
 status VARCHAR(16) NOT NULL DEFAULT 'UNPAID', created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), paid_at DATETIME(3) NULL,
 FOREIGN KEY(order_id) REFERENCES repair_order(id), FOREIGN KEY(quote_id) REFERENCES repair_quote(id),
 CHECK(amount_fen>0), CHECK(status IN ('UNPAID','MOCK_PAID'))
);
CREATE TABLE repair_payment (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, bill_id BIGINT NOT NULL UNIQUE, payment_no VARCHAR(64) NOT NULL UNIQUE,
 channel VARCHAR(16) NOT NULL, amount_fen BIGINT NOT NULL, status VARCHAR(16) NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 FOREIGN KEY(bill_id) REFERENCES repair_bill(id), CHECK(channel='MOCK'), CHECK(status='MOCK_SUCCESS')
);
