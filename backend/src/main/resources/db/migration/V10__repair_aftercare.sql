CREATE TABLE repair_aftercare (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 order_id BIGINT NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'REQUESTED',
 content VARCHAR(1000) NOT NULL,
 version INT NOT NULL DEFAULT 0,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 active_order BIGINT GENERATED ALWAYS AS (CASE WHEN status IN ('REQUESTED','PROCESSING','PENDING_CONFIRM') THEN order_id ELSE NULL END) STORED,
 UNIQUE KEY uq_aftercare_active(active_order),
 FOREIGN KEY(order_id) REFERENCES repair_order(id),
 CHECK(status IN ('REQUESTED','PROCESSING','PENDING_CONFIRM','CLOSED','REJECTED'))
);
CREATE TABLE repair_aftercare_log (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 aftercare_id BIGINT NOT NULL,
 operator_id BIGINT NOT NULL,
 status VARCHAR(24) NOT NULL,
 content VARCHAR(1000) NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 FOREIGN KEY(aftercare_id) REFERENCES repair_aftercare(id),
 FOREIGN KEY(operator_id) REFERENCES sys_user(id)
);
